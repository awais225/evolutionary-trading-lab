# ---- the mapping ----------------------------------------------------------- #
def hex_rgb(value: str):
    """`#3a2c10` -> `58, 44, 16` so an /opacity utility keeps its alpha."""
    m = re.fullmatch(r"#([0-9a-fA-F]{6})", value or "")
    if not m:
        return None
    h = m.group(1)
    return f"{int(h[0:2], 16)}, {int(h[2:4], 16)}, {int(h[4:6], 16)}"


def escape(cls: str) -> str:
    return "".join(("\\" + ch) if ch in "[]/:.#%()" else ch for ch in cls)


def declaration(cls: str):
    """CSS declarations for a single utility class, or None if unknown."""
    if cls in ("flex",): return "display: flex;"
    if cls == "inline-flex": return "display: inline-flex;"
    if cls == "grid": return "display: grid;"
    if cls == "block": return "display: block;"
    if cls == "inline-block": return "display: inline-block;"
    if cls == "hidden": return "display: none;"
    if cls == "table": return None                      # component class, styled above
    if cls == "flex-col": return "flex-direction: column;"
    if cls == "flex-row": return "flex-direction: row;"
    if cls == "flex-wrap": return "flex-wrap: wrap;"
    if cls == "flex-1": return "flex: 1 1 0%;"
    if cls == "shrink-0": return "flex: 0 0 auto;"
    if cls == "items-center": return "align-items: center;"
    if cls == "items-start": return "align-items: flex-start;"
    if cls == "items-end": return "align-items: flex-end;"
    if cls == "items-baseline": return "align-items: baseline;"
    if cls == "justify-between": return "justify-content: space-between;"
    if cls == "justify-center": return "justify-content: center;"
    if cls == "justify-end": return "justify-content: flex-end;"
    if cls == "justify-start": return "justify-content: flex-start;"
    if cls == "text-right": return "text-align: right;"
    if cls == "text-left": return "text-align: left;"
    if cls == "text-center": return "text-align: center;"
    if cls == "uppercase": return "text-transform: uppercase;"
    if cls == "normal-case": return "text-transform: none;"
    if cls == "underline": return "text-decoration: underline;"
    if cls == "truncate": return "overflow: hidden; text-overflow: ellipsis; white-space: nowrap;"
    if cls == "break-words": return "overflow-wrap: anywhere; word-break: break-word;"
    if cls == "break-all": return "word-break: break-all;"
    if cls == "whitespace-normal": return "white-space: normal;"
    if cls == "whitespace-nowrap": return "white-space: nowrap;"
    if cls == "leading-none": return "line-height: 1;"
    if cls == "leading-relaxed": return "line-height: 1.6;"
    if cls == "tracking-wider": return "letter-spacing: 0.6px;"
    if cls == "tracking-wide": return "letter-spacing: 0.3px;"
    if cls == "tracking-tight": return "letter-spacing: -0.2px;"
    if cls == "w-full": return "width: 100%;"
    if cls == "h-full": return "height: 100%;"
    if cls == "mx-auto": return "margin-left: auto; margin-right: auto;"
    if cls == "ml-auto": return "margin-left: auto;"
    if cls == "overflow-hidden": return "overflow: hidden;"
    if cls == "overflow-x-auto": return "overflow-x: auto;"
    if cls == "overflow-y-auto": return "overflow-y: auto;"
    if cls == "border": return "border: 1px solid var(--border);"
    if cls == "border-0": return "border: 0;"
    if cls == "border-b": return "border-bottom: 1px solid var(--border);"
    if cls == "border-t": return "border-top: 1px solid var(--border);"
    if cls == "border-l": return "border-left: 1px solid var(--border);"
    if cls == "border-r": return "border-right: 1px solid var(--border);"
    if cls == "divide-y": return None                    # handled with its colour partner
    if cls == "fixed": return "position: fixed;"
    if cls == "absolute": return "position: absolute;"
    if cls == "relative": return "position: relative;"
    if cls == "inset-0": return "inset: 0;"
    if cls == "z-50": return "z-index: 50;"
    if cls == "backdrop-blur-sm": return "backdrop-filter: blur(3px);"
    if cls == "cursor-pointer": return "cursor: pointer;"
    if cls == "pointer-events-none": return "pointer-events: none;"
    if cls == "transition-colors": return "transition: color .15s ease, background-color .15s ease, border-color .15s ease;"
    if cls == "transition-all": return "transition: all .18s ease;"
    if cls in ("animate-in", "fade-in"): return "animation: kitfade .22s ease both;"
    if cls == "font-mono": return "font-family: var(--mono);"
    if cls == "font-sans": return "font-family: inherit;"

    # state variants: `disabled:opacity-40` -> `.disabled\:opacity-40:disabled`
    m = re.fullmatch(r"(hover|focus|active|disabled):(.+)", cls)
    if m:
        return ("VARIANT", m.group(1), declaration(m.group(2)))

    # vertical rhythm helper (`space-y-3` = every child but the first)
