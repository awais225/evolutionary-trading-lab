def used_classes() -> "set[str]":
    used = set()
    for path in list(SRC.rglob("*.jsx")) + list(SRC.rglob("*.js")):
        text = path.read_text(encoding="utf-8", errors="replace")
        for m in re.finditer(r'className=(?:"([^"]*)"|\{`([^`]*)`\}|\{"([^"]*)"\})', text):
            raw = m.group(1) or m.group(2) or m.group(3) or ""
            for tok in re.split(r"[\s${}]+", raw):
                tok = tok.strip()
                if re.fullmatch(r"[a-zA-Z][-a-zA-Z0-9_:./\[\]]*", tok) and not tok.startswith("https"):
                    used.add(tok)
    return used


def handwritten_css() -> str:
    """The stylesheet WITHOUT this generator's own block (keeps the run idempotent)."""
    text = CSS.read_text(encoding="utf-8")
    if BEGIN in text and END in text:
        text = text[:text.index(BEGIN)] + text[text.index(END) + len(END):]
    return text


def defined_classes() -> "set[str]":
    return set(re.findall(r"\.((?:[a-zA-Z0-9_-]|\\.)+)", handwritten_css()))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    css_text = handwritten_css().rstrip("\n") + "\n"
    defined = defined_classes()
    used = used_classes()

    # classes that are dynamic expressions leaked by the regex - never real class names
    dynamic = {c for c in used if re.search(r"[.=()\[\]]", c) and not c.startswith(("text-[", "max-w-", "min-w-"))}
    dynamic |= {c for c in used if c in {
        "tone", "isRunning", "allowed", "connected", "activePopover", "detailTab", "cat", "isStar",
        "status", "ok", "net_profit", "requireText", "population", "source", "is_stalled",
        "promoted_to_paper", "SHORTLISTED", "s", "ghost", "primary", "danger", "success", "warn",
        "mute", "info", "accent", "sim", "real", "violet", "good", "bad", "compact", "table",
        "num", "clickable", "selected", "is-selected", "input", "field", "stack", "row-bar",
        "spacer", "page", "chk", "cols-5", "cols-6", "top-status-row", "table-wrap", "scroll-x",
        "kit-col", "kit-grid", "kit-kpi-row", "kit-pager", "kit-inline-ok", "kit-summary",
        "error-note", "modal-content", "status-pill", "status-row-item", "panel-title",
        "section-title", "metric-grid", "btn-sm", "btn-xs", "btn-subtle", "btn-primary", "btn-icon",
        "icon", "sm", "xs", "lg", "xl",
    }}

    dynamic |= DYNAMIC_EXTRA
    missing = sorted(c for c in used if c not in defined and c not in dynamic and c not in SEMANTIC)
    rows: "list[tuple[str, object]]" = []
    unmapped: "list[str]" = []
    for cls in missing:
        decl = declaration(cls)
        if decl is None:
            # `divide-y` + `divide-<colour>` are emitted as child-selector rules
            if cls in ("divide-y", "table") or cls.startswith("divide-"):
                continue
            unmapped.append(cls)
        else:
            rows.append((cls, decl))

    # the divide-* family: a single rule that uses the colour of its partner class
    divide_rules = []
    if any(c.endswith("divide-slate-800/60") for c in used):
        divide_rules.append(".divide-slate-800\\/60 > * + * { border-top: 1px solid rgba(35, 43, 61, .6); }")
    if any(c.endswith("divide-rose-800/60") for c in used):
        divide_rules.append(".divide-rose-800\\/60 > * + * { border-top: 1px solid rgba(111, 38, 38, .6); }")

    print(f"used: {len(used)}  defined: {len(defined)}  to generate: {len(rows)}  unmapped: {len(unmapped)}")
    if unmapped:
        print("UNMAPPED (no rule will be emitted):")
        for c in sorted(set(unmapped)):
            print(f"   {c}")
    if args.check:
        return 1 if unmapped else 0

    lines = []
    for cls, decl in sorted(rows):
        if isinstance(decl, tuple):
            if decl[0] == "VARIANT":
                state, inner = decl[1], decl[2]
                if isinstance(inner, tuple):            # e.g. disabled:cursor-not-allowed
                    inner = inner[1] if inner[0] == "CHILDREN" else None
                if inner:
                    lines.append(f".{escape(cls)}:{state} {{ {inner} }}")
            elif decl[0] == "CHILDREN":
                lines.append(f".{escape(cls)} > * + * {{ {decl[1]} }}")
        else:
            lines.append(f".{escape(cls)} {{ {decl} }}")
    lines.append("@keyframes kitfade { from { opacity: 0; transform: translateY(2px); } "
                 "to { opacity: 1; transform: none; } }")
    body = "\n".join(lines)
    section = f"\n{BEGIN}\n{body}\n" + ("\n".join(divide_rules) + "\n" if divide_rules else "") + f"{END}\n"

    # idempotent: replace the previous generated block if present
    if BEGIN in css_text and END in css_text:
        start = css_text.index(BEGIN)
        stop = css_text.index(END) + len(END) + 1
        css_text = css_text[:start] + section.lstrip("\n") + css_text[stop:]
    else:
        css_text = css_text.rstrip("\n") + "\n" + section
    CSS.write_text(css_text, encoding="utf-8")
    print(f"wrote {len(rows)} utility rules into {CSS.name} (+{len(divide_rules)} divide rules)")
    return 0


