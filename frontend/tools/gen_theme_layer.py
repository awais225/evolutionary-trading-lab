def sp(value: str):
    """Tailwind's spacing scale: n = n * 4px (0.5 -> 2px, 1.5 -> 6px, 24 -> 96px)."""
    try:
        n = float(value)
    except ValueError:
        return None
    return f"{n * 4:g}px"
