"""Historical market-data endpoints: availability + incremental MT5 fetch.

Availability reads the canonical store only (no terminal needed). Fetch
requires a live MT5 session and never fabricates a result: without the
terminal it answers 503 MT5_UNAVAILABLE, and per-timeframe failures are
reported inside the fetch report - never as SUCCESS.
"""
from __future__ import annotations

from typing import Optional

from fastapi import APIRouter, Depends, HTTPException
from pydantic import BaseModel, Field

from app import market_data_service
from app.deps import get_instrument_context
from hero1_eventbus import get_event_publisher
from hero1_market_data.store import TIMEFRAME_ORDER, TIMEFRAME_STEPS

router = APIRouter(prefix="/api/v1/instruments/{instrument}/market-data", tags=["market-data"])


class FetchRequest(BaseModel):
    timeframe: str = Field(default="ALL", description="ALL or one of M1 M5 M15 M30 H1 H4 D1")
    operation_id: Optional[str] = Field(default=None, max_length=64,
                                        description="client-generated fetch trace id; "
                                                    "generated by the server when omitted")


@router.get("")
def read_availability(instrument: str = Depends(get_instrument_context)) -> dict:
    """Stored historical coverage for this instrument, per timeframe (read-only)."""
    return market_data_service.availability(instrument)


@router.post("/fetch/start")
def start_fetch_data(body: Optional[FetchRequest] = None,
                     instrument: str = Depends(get_instrument_context)) -> dict:
    """Start a fetch as a BACKGROUND operation (202-style contract).

    The HTTP request returns immediately with the operation id; the DATA
    tab polls the operation status, so a slow terminal can never wedge the
    UI or the server, navigation never loses the operation, and a second
    click returns the already-running operation instead of duplicating it.
    """
    tf = (body.timeframe if body else "ALL").strip().upper()
    if tf == "ALL":
        timeframes = list(TIMEFRAME_ORDER)
    elif tf in TIMEFRAME_STEPS:
        timeframes = [tf]
    else:
        raise HTTPException(422, detail={"code": "TIMEFRAME_UNSUPPORTED",
                                         "message": f"timeframe must be ALL or one of "
                                                    f"{', '.join(TIMEFRAME_ORDER)}; got {tf!r}"})
    started = market_data_service.start_fetch(
        instrument, timeframes, operation_id=(body.operation_id if body else None))
    try:
        from app import task_service
        from app.deps import get_registry_session as _grs
        _reg = next(_grs())
        try:
            if not started.get("existing"):
                task_service.create_task(
                    _reg, category="DATA_FETCHING", instrument=instrument,
                    label=f"Fetch {tf} [{instrument}]",
                    total_units=len(timeframes),
                    payload={"operation_id": started["operation_id"],
                             "timeframes": timeframes})
        finally:
            _reg.close()
    except Exception:  # noqa: BLE001 - progress bookkeeping never breaks fetching
        pass
    get_event_publisher().publish(
        category="SYSTEM", severity="INFO", subsystem="market-data",
        message=f"[{started['operation_id']}] FETCH operation {'already running' if started['existing'] else 'started'} [{instrument}] {tf}",
        instrument=instrument,
        payload={"operation_id": started["operation_id"], "stage": "OPERATION_CREATED",
                 "timeframe": tf, "existing": started["existing"]})
    return started


@router.get("/fetch/operations/{operation_id}")
def fetch_operation(operation_id: str,
                    instrument: str = Depends(get_instrument_context)) -> dict:
    rec = market_data_service.operation_status(operation_id)
    if rec is None or rec["instrument"] != instrument:
        raise HTTPException(404, detail={"code": "OPERATION_NOT_FOUND",
                                         "message": f"no fetch operation {operation_id!r} for {instrument}"})
    return rec


@router.get("/fetch/operations")
def latest_fetch_operation(instrument: str = Depends(get_instrument_context)) -> dict:
    rec = market_data_service.latest_operation(instrument)
    return rec or {"operation_id": None, "state": "IDLE", "instrument": instrument,
                   "timeframes": [], "report": None, "error": None}


@router.post("/fetch")
def fetch_data(body: Optional[FetchRequest] = None,
               instrument: str = Depends(get_instrument_context)) -> dict:
    """Fetch completed candles from the connected MT5 terminal and append
    only genuinely new ones to the canonical store (see market_data_service)."""
    tf = (body.timeframe if body else "ALL").strip().upper()
    if tf == "ALL":
        timeframes = list(TIMEFRAME_ORDER)
    elif tf in TIMEFRAME_STEPS:
        timeframes = [tf]
    else:
        raise HTTPException(422, detail={"code": "TIMEFRAME_UNSUPPORTED",
                                         "message": f"timeframe must be ALL or one of "
                                                    f"{', '.join(TIMEFRAME_ORDER)}; got {tf!r}"})
    try:
        report = market_data_service.fetch(instrument, timeframes,
                                           operation_id=(body.operation_id if body else None))
    except market_data_service.FetchError as exc:
        raise HTTPException(exc.status_code, detail={"code": exc.code, "message": exc.message}) from exc
    get_event_publisher().publish(
        category="SYSTEM", severity="INFO", subsystem="market-data",
        message=(f"MT5 fetch [{instrument}] {tf}: "
                 + ", ".join(f"{r['timeframe']}={r['status']}(+{r['appended']})" for r in report["results"])),
        payload={"instrument": instrument, "timeframe": tf, "ok": report["ok"],
                 "operation_id": report.get("operation_id"),
                 "broker_server": report["broker_server"]})
    return report


class ConflictResolveRequest(BaseModel):
    action: str = Field(description="KEPT_STORED | ACCEPTED_INCOMING")
    note: Optional[str] = Field(default=None, max_length=1000)


@router.get("/conflicts")
def list_fetch_conflicts(instrument: str = Depends(get_instrument_context),
                         operation_id: Optional[str] = None,
                         resolution: Optional[str] = None,
                         limit: int = 200) -> dict:
    """Durable fetch-conflict audit (ISSUE-054): stored vs incoming values,
    provenance and resolution state for every conflict ever recorded."""
    return market_data_service.list_conflicts(
        instrument, operation_id=operation_id, resolution=resolution, limit=limit)


@router.post("/conflicts/{conflict_id}/resolve")
def resolve_fetch_conflict(conflict_id: int, body: ConflictResolveRequest,
                           instrument: str = Depends(get_instrument_context)) -> dict:
    """Controlled correction of ONE conflict. ACCEPTED_INCOMING replaces the
    stored candle with the MT5 values (pre-resolution values stay on the
    audit row as backup + a full audit event); KEPT_STORED just records the
    decision. Never silent, never bulk."""
    if body.action not in ("KEPT_STORED", "ACCEPTED_INCOMING"):
        raise HTTPException(422, detail={"code": "RESOLUTION_ACTION_INVALID",
                                         "message": "action must be KEPT_STORED or ACCEPTED_INCOMING"})
    try:
        return market_data_service.resolve_conflict(instrument, conflict_id,
                                                    body.action, body.note)
    except KeyError as exc:
        raise HTTPException(404, detail={"code": "CONFLICT_NOT_FOUND", "message": str(exc)}) from None
    except ValueError as exc:
        raise HTTPException(409, detail={"code": "CONFLICT_ALREADY_RESOLVED", "message": str(exc)}) from None


@router.get("/quality")
def read_data_quality(instrument: str = Depends(get_instrument_context),
                      timeframe: str = "M15",
                      from_ts: Optional[int] = None,
                      to_ts: Optional[int] = None) -> dict:
    """Backtesting-readiness report (ISSUE-055 B7): coverage, unverified
    gaps, unresolved conflicts, sources, READY/CAUTION/NOT_READY."""
    try:
        return market_data_service.data_quality(instrument, timeframe,
                                                from_epoch=from_ts, to_epoch=to_ts)
    except ValueError as exc:
        raise HTTPException(422, detail={"code": "TIMEFRAME_UNSUPPORTED", "message": str(exc)}) from None

