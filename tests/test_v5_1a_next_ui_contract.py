def test_08_the_selector_is_one_component_used_by_both_mt5_pages():
    assert SELECTOR.exists()
    for rel in ("pages/Mt5DemoTrading.jsx", "pages/LiveTesting.jsx"):
        src = (SRC / rel).read_text(encoding="utf-8")
        assert "Mt5AccountSelector" in src, rel
        assert "<Mt5AccountSelector" in src, rel


def test_09_the_selector_is_backend_driven():
    src = SELECTOR.read_text(encoding="utf-8")
    assert "api.mt5Accounts" in src and "api.mt5AccountSelect" in src
    # no hard-coded account list / account numbers
    assert not re.search(r"\b\d{7,}\b", src), "an account number appears to be hard-coded"


def test_10_a_real_account_stays_visibly_refused():
    src = SELECTOR.read_text(encoding="utf-8")
    assert "REAL ACCOUNT DETECTED — ORDERS ARE REFUSED." in src
    assert "does not make it tradable" in src or "the demo guard refuses" in src.lower()


def test_11_the_selector_never_claims_a_probe_or_a_trade_it_did_not_do():
    src = SELECTOR.read_text(encoding="utf-8")
    assert "never sends an order" in src
    assert "Accounts are not probed yet" in src          # the honest "not probed" state
    assert "not importable in this interpreter" in src    # the honest unavailable state


def test_12_the_api_client_exposes_the_new_endpoints():
    src = (SRC / "api.js").read_text(encoding="utf-8")
    assert "/api/mt5/accounts" in src
    assert "/api/mt5/accounts/select" in src
    assert "/api/nodes/populations" in src


def test_13_the_selector_uses_the_shared_kit_components():
    src = SELECTOR.read_text(encoding="utf-8")
    for sym in ("Card", "Badge", "StateBlock"):
        assert sym in src, sym
    # no invented class names: everything here is in the theme layer
    classes = set(re.findall(r'className="([^"]+)"', src))
    known = set(re.findall(r"\.([a-zA-Z][\w-]*)", CSS.read_text(encoding="utf-8")))
    unknown = {c for group in classes for c in group.split() if c not in known}
    assert unknown == set(), unknown
